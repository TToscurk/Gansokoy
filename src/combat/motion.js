// --- 編譯：把每套動作的欄位補滿，插值時就不必再判斷缺欄 -------------------
const VEC = { aR: 3, aL: 3, wrist: 3, legs: 2 };

const MOTIONS = {};
for (const [name, keys] of Object.entries(RAW)) {
  const used = new Set();
  for (const k of keys) for (const f of Object.keys(k)) if (f !== 't') used.add(f);

  MOTIONS[name] = {
    fields: [...used],
    keys: keys.map(k => {
      const out = { t: k.t };
      for (const f of used) {
        const v = k[f] ?? DEF[f];
        out[f] = VEC[f] ? v.slice() : v;
      }
      return out;
    }),
  };
}

export const MOTION_NAMES = Object.keys(MOTIONS);

const smooth = t => t * t * (3 - 2 * t);

/**
 * 取某套動作在進度 k（0~1）的姿勢。
 * 回傳物件只含這套動作真的有在動的欄位 —— 沒寫的欄位由呼叫端自行保留。
 */
export function poseFor(name, k) {
  const m = MOTIONS[name] || MOTIONS.guard;
  const t = k < 0 ? 0 : k > 1 ? 1 : k;

  let i = 0;
  while (i < m.keys.length - 2 && m.keys[i + 1].t < t) i++;
  const a = m.keys[i], b = m.keys[i + 1] ?? a;
  const span = b.t - a.t;
  const u = span > 1e-6 ? smooth((t - a.t) / span) : 0;

  const pose = {};
  for (const f of m.fields) {
    const n = VEC[f];
    if (n) {
      const av = a[f], bv = b[f], arr = new Array(n);
      for (let j = 0; j < n; j++) arr[j] = av[j] + (bv[j] - av[j]) * u;
      pose[f] = arr;
    } else {
      pose[f] = a[f] + (b[f] - a[f]) * u;
    }
  }
  return pose;
}

/** 把姿勢寫進骨架。缺欄位＝不覆寫（讓走路動畫繼續管那個部位）。 */
export function applyPose(rig, pose) {
  if (pose.aR && rig.armR) rig.armR.rotation.set(pose.aR[0], pose.aR[1], pose.aR[2]);
  if (pose.aL && rig.armL) rig.armL.rotation.set(pose.aL[0], pose.aL[1], pose.aL[2]);
  if (rig.body) {
    rig.body.rotation.set(pose.pitch ?? 0, pose.yaw ?? 0, pose.roll ?? 0);
    // 疊在 animateCharacter 算好的呼吸起伏上。寫絕對值而非 += ——
    // 同一幀被呼叫兩次也不會把人越推越低。
    rig.body.position.y = (rig.bobY ?? 0) + (pose.dy ?? 0);
  }
  if (pose.legs) {
    if (rig.legL) rig.legL.rotation.x = pose.legs[0];
    if (rig.legR) rig.legR.rotation.x = pose.legs[1];
  }
}

