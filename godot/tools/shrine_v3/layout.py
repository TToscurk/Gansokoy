def stair_profile():
    """回傳 (z_foot, segments)。由上往下，第 k 升（1..90）落到面 S_k（頂高 P − k·rise）：
    一段的最後一升落到中間平台（深 landing）；第 90 升落到石階腳地面（不建面）；其餘是踏面（深 run）。
    segments：[(z_a, z_b, y_top, kind, flight)]。"""
    st = STAIR
    z = st['z_top']
    segs = []
    k = 0
    for fi, n in enumerate(st['flights']):
        for i in range(n):
            k += 1
            y = P - k * st['rise']
            if k == st['rises']:
                return z, segs
            if i == n - 1:
                segs.append((z, z + st['landing'], y, 'landing', fi))
                z += st['landing']
            else:
                segs.append((z, z + st['run'], y, 'tread', fi))
                z += st['run']
    return z, segs


