def sando_hw(z):
    """參道鋪石半寬（公尺）；z 在範圍外回 0。make_site.py、gen_terrain.py、build_scene.gd 共用同一定義。"""
    s = SANDO
    if z > s['z0'] or z < s['z1']:
        return 0.0
    if z >= s['torii_z']:
        return s['torii_hw']
    if z >= s['nat_z']:
        t = min(max((s['torii_z'] - z) / 0.8, 0.0), 1.0)
        hw = s['torii_hw'] + (s['nat_hw'] - s['torii_hw']) * t
        u = min(max((s['nat_z'] + 0.8 - z) / 0.8, 0.0), 1.0)
        return hw + (s['mid_hw'] - hw) * u
    if z >= s['fan_z0']:
        return s['mid_hw']
    if z >= s['fan_z1']:
        t = (s['fan_z0'] - z) / (s['fan_z0'] - s['fan_z1'])
        t = t * t * (3 - 2 * t)
        return s['mid_hw'] + (s['apron_hw'] - s['mid_hw']) * t
    return s['apron_hw']


